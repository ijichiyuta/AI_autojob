-- ============================================================
-- コンペ形式を即時除外に追加
--
-- 要件定義 5.2 は「契約前のテスト課題が無償」を即時除外としているが、
-- コンペは構造的にこれと同じ（成果物を作って提出し、選ばれなければ報酬ゼロ）。
-- 週20時間しか動けない前提では「低単価案件で工数だけ溶ける」リスクそのものなので、
-- テスト課題と同格で扱う。
--
-- 実例: ダイアログ・イン・ザ・ダークのLPコンペ（賞金7万円）。
-- 要件の質は高いが、PC/SP両方のモックアップを作って落選すればゼロ。
-- ============================================================
update public.settings
set value = value || jsonb_build_array(
  jsonb_build_object(
    'id', 'competition',
    'type', 'ng',
    'label', 'コンペ形式（落選すると報酬ゼロ）',
    'note', '成果物を作ってから選考される。無償テスト課題と同じ構造として扱う',
    'patterns', jsonb_build_array(
      'コンペ(を|形式|方式|に|の)',
      'コンペ賞金',
      '(採用|選出|当選)された方(のみ|だけ)[^。\n]{0,12}(報酬|お支払い)',
      '(ラフ案|モックアップ|ワイヤー)[^。\n]{0,16}(ご提示|ご提出|応募)[^。\n]{0,12}(ください|お願い)'
    )
  )
)
where key = 'ng_rules';
