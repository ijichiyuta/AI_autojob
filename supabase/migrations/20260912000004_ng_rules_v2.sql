-- ============================================================
-- NG判定ルール v2
-- 初回クロールで判明した取りこぼしへの対応:
--   ① 「クラウドワークス テック」等の月額常駐型（毎月160時間稼働）が上位を占めた
--      → 週20時間（月約87時間）の稼働上限を超える案件を除外する
--   ② 同種の案件は応募が外部サイト（tech.crowdworks.jp）に誘導され、
--      サイト内の応募機能が使えない → 自動応募の対象外なので除外する
-- ============================================================

update public.settings
set value = (
  select jsonb_agg(
    case
      when rule->>'id' = 'onsite' then jsonb_build_object(
        'id', 'onsite',
        'type', 'ng',
        'label', '常駐・出社・稼働時間拘束',
        'note', '本業フルタイムのため平日日中は対応不可',
        'patterns', jsonb_build_array(
          '(常駐|出社|オフィス(勤務|作業)|来社|対面(での)?(打ち合わせ|MTG|面談)(必須|必要))',
          '(平日|日中)[^。\n]{0,8}(対応|稼働|連絡|勤務)(可能|できる|必須|必要)',
          '(即レス|即時|リアルタイム)[^。\n]{0,6}(対応|返信)(必須|必要|できる)',
          '(毎日|日次)[^。\n]{0,6}(定例|MTG|ミーティング|報告)(必須|あり)'
        )
      )
      else rule
    end
  )
  from jsonb_array_elements(value) as rule
)
where key = 'ng_rules';

