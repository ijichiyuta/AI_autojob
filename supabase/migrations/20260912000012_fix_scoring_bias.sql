-- ============================================================
-- ① 資格必須・実名顔出しの案件を即時除外に追加
--    「眼科医の方限定」「歯科医師の免許をお持ちの方」といった商品監修案件が
--    時給の高さで最上位を占めていた。応募資格がそもそも無く、
--    実名・顔写真の公表が条件で匿名運用の方針とも衝突する。
-- ============================================================
update public.settings
set value = value || jsonb_build_array(
  jsonb_build_object(
    'id', 'license_required',
    'type', 'ng',
    'label', '資格・免許が必須',
    'note', '医師・弁護士等の有資格者限定の監修案件。応募資格がない',
    'patterns', jsonb_build_array(
      '(医師|歯科医師|眼科医|内科医|弁護士|税理士|会計士|社労士|司法書士|行政書士|看護師|薬剤師|保育士|管理栄養士|栄養士|建築士|整備士|美容師|調理師|臨床心理士|キャリアコンサルタント)[^。\n]{0,12}(の方|資格|免許)[^。\n]{0,12}(限定|募集|お持ち|保有|必須)',
      '(免許|国家資格)[^。\n]{0,10}(をお持ち|保有|所持)[^。\n]{0,10}(の方|が必須|限定)',
      '(商品|記事|コンテンツ)監修(者|していただける方)?[^。\n]{0,10}(募集|探し|協力)'
    )
  ),
  jsonb_build_object(
    'id', 'identity_disclosure',
    'type', 'ng',
    'label', '実名・顔写真の公表が条件',
    'note', '本業に知られない前提で運用しているため受けられない',
    'patterns', jsonb_build_array(
      '(実名|本名)[^。\n]{0,14}(公表|掲載|開示|記載)',
      '(顔写真|お顔|顔出し)[^。\n]{0,14}(公表|掲載|提供|必須|OK|可能な方)'
    )
  )
)
where key = 'ng_rules';

-- ============================================================
-- ② 重みの再配分
--    応募数の重みを時給へ全部寄せたのが行き過ぎだった。
--    得意ジャンルとの一致度が90でも9点しか付かず、時給の高い畑違いの案件に負けていた。
--    時給を30に戻し、その10点をジャンル一致に回す。
--    応募数の5は維持する（応募多数を足切りにしない方針は変えない）。
-- ============================================================
update public.settings
set value = '{
  "hourly_rate":      30,
  "client_quality":   20,
  "low_competition":   5,
  "specificity":      15,
  "genre_match":      20,
  "deadline_margin":  10
}'::jsonb
where key = 'scoring_weights';
