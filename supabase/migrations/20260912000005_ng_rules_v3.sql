-- ============================================================
-- NG判定ルール v3
-- 40件の案件文を実際に読んで判明した取りこぼし:
--   ① SES系案件に「副業NG」「稼働140-180h」の明記がある（v2の正規表現は「月」始まりのみ対応）
--   ② 「東京在住、または都内でのオフライン打ち合わせに参加可能な方」の地域条件
--   ③ 報酬を提示せず「このチャットへ興味ありますとご返信ください」だけの募集が連投されている
--   ④ 「顔出しのZOOM必須」は匿名運用の方針と衝突する
-- ============================================================

update public.settings
set value = value || jsonb_build_array(
  jsonb_build_object(
    'id', 'side_job_prohibited',
    'type', 'ng',
    'label', '副業不可・専業限定',
    'note', '本業（日本ガイシ）を持つ前提と正面から衝突する',
    'patterns', jsonb_build_array(
      '副業\s*(は)?\s*(NG|ng|不可|禁止|お断り|できません)',
      '(専業|メイン)[^。\n]{0,8}(の方|として)[^。\n]{0,10}(のみ|限定|募集)',
      'メインの案件として対応可能',
      '(他社|他の)案件[^。\n]{0,10}(掛け持ち|兼務)[^。\n]{0,6}(不可|NG)'
    )
  ),
  jsonb_build_object(
    'id', 'business_hours',
    'type', 'ng',
    'label', '平日日中の稼働が前提',
    'note', '本業が平日8:30〜17:15のため対応できない',
    'patterns', jsonb_build_array(
      '一般ビジネスタイム',
      '1[0-9]{2}\s*[-〜~ー]\s*1[0-9]{2}\s*(h|時間)',
      '週\s*[2-6]\s*[〜~ー-]\s*[3-7]\s*日',
      '(平日|営業日)[^。\n]{0,6}(9|九)[:：時][^。\n]{0,10}(1[0-9]|2[0-4])[:：時]',
      '(日中|営業時間内)[^。\n]{0,8}(連絡|対応|稼働)[^。\n]{0,6}(可能|必須|取れる)'
    )
  ),
  jsonb_build_object(
    'id', 'location_restricted',
    'type', 'ng',
    'label', '地域限定（名古屋圏以外）',
    'note', '愛知・名古屋・東海は対象外にしてある',
    'patterns', jsonb_build_array(
      '(東京|都内|大阪|福岡|札幌|横浜|仙台|関東|首都圏|近畿)[^。\n]{0,8}(在住|近郊|にお住まい|勤務)[^。\n]{0,10}(の方|限定|必須|可能|歓迎)',
      '(オフライン|対面|現地)[^。\n]{0,10}(打ち合わせ|MTG|ミーティング|面談|作業)[^。\n]{0,10}(参加|来社|可能な方|必須)'
    )
  ),
  jsonb_build_object(
    'id', 'chat_funnel',
    'type', 'ng',
    'label', '報酬未提示のチャット誘導',
    'note', '業務範囲も報酬も書かず「興味あります」と返信させるだけの募集。応募文も価格も生成できない',
    'patterns', jsonb_build_array(
      '(この|本)チャット[^。\n]{0,12}(興味あります|ご返信|返信して)',
      '報酬[：:\s]*(実績|案件への貢献度|経験)[^。\n]{0,16}(応じて)[^。\n]{0,12}(個別|別途)?[^。\n]{0,6}(ご)?相談',
      '折り返し[^。\n]{0,10}(詳細|詳しい)[^。\n]{0,10}(ご案内|送付)'
    )
  ),
  jsonb_build_object(
    'id', 'face_required',
    'type', 'warn',
    'label', '顔出し必須',
    'note', '本業に知られない前提で運用しているため、顔出しは避けたい',
    'patterns', jsonb_build_array(
      '顔出し[^。\n]{0,10}(ZOOM|Zoom|zoom|面談|MTG|打ち合わせ)',
      '(カメラ|ビデオ)(オン|ON)[^。\n]{0,10}(必須|でお願い)'
    )
  ),
  jsonb_build_object(
    'id', 'budget_mismatch',
    'type', 'warn',
    'label', '掲載予算と実際の報酬が乖離',
    'note', '掲載予算は高いが、本文では単価数百円〜数千円を指定しているケース',
    'patterns', jsonb_build_array(
      '固定報酬\s*[0-9,]{3,6}\s*円に設定',
      '[0-9,]{3,4}\s*円に設定(の上|して)[^。\n]{0,10}応募'
    )
  )
)
where key = 'ng_rules';
